#!/usr/bin/env python3
"""The libgxm porting map: what Sony's GXM library does, from the firmware itself, merged with the
SDK headers' names and types.

  gxmmap.py <libgxm_es4.suprx.elf> <psp2/gxm.h> [out.md]

For every exported function: its signature (the headers), its class -- PURE when nothing it can
reach calls the GPU driver (SceGpuEs4*: those functions can run as Sony's code, recompiled like
libc) or GPU when something does (the boundary our host implements) -- its size, and the kernel
imports it reaches. For the context setters (sceGxmSet*, surfaces, textures): the stores each makes,
which with the headers' pre-shifted enum values give the hardware words and their bit positions; and
the context layout by offset with every function that writes each field.

Reads a console's own decrypted firmware; the map it writes stays out of the repository like any
other output derived from Sony code (dump/ is gitignored) unless reviewed.
"""
import os, re, sys
from collections import defaultdict
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "..", "..", "recompiler"))   # (platmap beside this; analyze in the recompiler)
from analyze import Module, Analyser
from capstone import Cs, CS_ARCH_ARM, CS_MODE_ARM, CS_MODE_THUMB
from capstone import arm as A


def nid_names():
    names = {}
    for l in open(os.path.join(HERE, "..", "..", "decrypt", "nidmap.tsv")):
        p = l.rstrip("\n").split("\t")
        if len(p) >= 3:
            names[(p[0], int(p[1], 16))] = p[2]
    return names


def prototypes(header):
    """function name -> its declaration, one line, from the header"""
    src = re.sub(r"/\*.*?\*/", "", open(header).read(), flags=re.S)
    src = re.sub(r"//[^\n]*", "", src)
    out = {}
    for m in re.finditer(r"([A-Za-z_][\w \*]*?)\b(sceGxm\w+)\s*\(([^;{]*?)\)\s*;", src):
        out[m.group(2)] = re.sub(r"\s+", " ", f"{m.group(1).strip()} {m.group(2)}({m.group(3).strip()})")
    return out


def main():
    if len(sys.argv) < 3:
        print(__doc__); sys.exit(1)
    elf, header = sys.argv[1], sys.argv[2]
    out = open(sys.argv[3], "w") if len(sys.argv) > 3 else sys.stdout
    names, protos = nid_names(), prototypes(header)
    m = Module(elf)
    text = m.loads[0]
    an = Analyser(m, text[2], text[2] + text[4])
    code, base = m.mem[text[2]], text[2]

    stub = {}
    for lib, fns, _ in m.imports():
        for nid, a in fns:
            stub[a & ~1] = (lib, names.get((lib, nid), f"{lib}_{nid:08X}"))
    exports = [(names.get((lib, nid), f"{lib}_{nid:08X}"), a) for lib, nid, a, var in m.export_table() if not var and lib.startswith("SceGxm")]

    # every function reachable from the exports, its direct calls (calls into exports end at them)
    entries = {a & ~1 for _, a in exports} | set(stub)
    calls, size, todo, seen = {}, {}, [(a & ~1, not a & 1) for _, a in exports], set()
    while todo:
        f, arm = todo.pop()
        if f in seen or f in stub:
            continue
        seen.add(f)
        r = an.function(f, arm, entries)
        if r is None:
            calls[f] = set(); continue
        insns, fcalls = r[0], r[1]
        size[f] = sum(insns.values())
        calls[f] = {t & ~1 for t, _ in fcalls}
        todo += [(t & ~1, tarm) for t, tarm in fcalls if (t & ~1) not in stub]

    memo = {}
    def reach(f, stack=frozenset()):
        if f in memo: return memo[f]
        if f in stack: return set()
        got = set()
        for t in calls.get(f, ()):
            got |= {stub[t]} if t in stub else reach(t, stack | {f})
        memo[f] = got
        return got

    def stores(a):
        """the stores of a setter's straight-line body, to its first return"""
        md = Cs(CS_ARCH_ARM, CS_MODE_THUMB if a & 1 else CS_MODE_ARM); md.detail = True
        got = []
        for i in md.disasm(bytes(code[(a & ~1) - base:(a & ~1) - base + 0x300]), a & ~1):
            mem = [o for o in i.operands if o.type == A.ARM_OP_MEM]
            if (i.mnemonic.startswith("str") or i.mnemonic.startswith("vstr")) and mem:
                got.append((i.mnemonic, i.reg_name(mem[0].mem.base), mem[0].mem.disp, i.op_str))
            if i.mnemonic == "bx" or ("pc" in i.op_str and (i.mnemonic.startswith("pop") or i.mnemonic.startswith("ldm"))):
                break
        return got

    rows = []
    for nm, a in sorted(exports):
        r = reach(a & ~1)
        gpu = sorted({n for l, n in r if l.startswith("SceGpu")})
        kern = sorted({n for l, n in r if not l.startswith("SceGpu") and not n.startswith("sceClib") and n != "__stack_chk_fail"})
        rows.append((nm, a, "GPU" if gpu else "PURE", size.get(a & ~1, 0), gpu, kern))

    w = out.write
    npure = sum(1 for r in rows if r[2] == "PURE")
    w(f"# libgxm porting map\n\nGenerated by `dev/research/gxmmap.py` from `{os.path.basename(elf)}` and `{header.split('/include/')[-1]}`.\n\n")
    w(f"{len(rows)} exported functions: **{npure} PURE** (nothing they can reach calls the GPU driver: run them as Sony's code, "
      f"recompiled like libc), **{len(rows) - npure} GPU** (they reach `SceGpuEs4*`: the boundary the host implements).\n\n")
    w("Imports (what the PURE side needs from the host):\n\n")
    for lib, fns, vs in m.imports():
        w(f"- `{lib}`: " + ", ".join(names.get((lib, n), f"{n:08X}") for n, _ in fns) + (f" (+{len(vs)} variable)" if vs else "") + "\n")

    w("\n## The GPU boundary\n\n| function | size | GPU calls | kernel calls | signature |\n|---|---|---|---|---|\n")
    for nm, a, cls, sz, gpu, kern in rows:
        if cls == "GPU":
            w(f"| `{nm}` | {sz} | {len(gpu)} | {', '.join(kern) or '-'} | `{protos.get(nm, '?')}` |\n")

    w("\n## Context layout (from the setters' stores)\n\nThe context argument arrives in r0; offsets are from it. "
      "Every setter also marks a dirty word, which shows up as one of the most-written offsets below.\n\n")
    by_off = defaultdict(list)
    per_fn = {}
    for nm, a, cls, sz, gpu, kern in rows:
        if cls != "PURE" or not nm.startswith("sceGxmSet"):
            continue
        st = stores(a)
        per_fn[nm] = st
        for mnem, b, disp, ops in st:
            if b == "r0":
                by_off[disp].append(nm)
    w("| offset | written by |\n|---|---|\n")
    for off in sorted(by_off):
        fns = sorted(set(by_off[off]))
        w(f"| `+{off:#05x}` | {', '.join(f'`{f}`' for f in fns[:12])}{' …' if len(fns) > 12 else ''} ({len(fns)}) |\n")

    w("\n## Setters\n\n| function | signature | stores |\n|---|---|---|\n")
    for nm in sorted(per_fn):
        w(f"| `{nm}` | `{protos.get(nm, '?')}` | {' ; '.join(f'`{m} {o}`' for m, b, d, o in per_fn[nm][:10])} |\n")

    w("\n## The PURE side\n\n| function | size | kernel calls | signature |\n|---|---|---|---|\n")
    for nm, a, cls, sz, gpu, kern in rows:
        if cls == "PURE":
            w(f"| `{nm}` | {sz} | {', '.join(kern) or '-'} | `{protos.get(nm, '?')}` |\n")


if __name__ == "__main__":
    main()
