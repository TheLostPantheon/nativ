#!/usr/bin/env python3
"""A porting map of one user-mode firmware library: for every function it exports, PURE (nothing it
reaches, across user modules, is a system call: run Sony's code) or BOUNDARY (the system calls it
reaches: what the host implements under it), its size, its signature from the SDK headers, and --
for the small functions that keep state in a struct (setters, getters, init) -- the struct offsets
they store to and load from, which give that object's layout the way they gave libgxm's context.

  libmap.py <module .suprx.elf | library name> [--headers <vita-headers dir>] [--out map.md]

A library name (SceLibKernel, SceAppUtil, ...) picks the firmware module exporting it. Uses
platmap.py's index of every module in the dump. The map is derived from Sony code and stays local.
"""
import glob, os, re, sys
from collections import defaultdict
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "..", "..", "recompiler"))   # (platmap beside this; analyze in the recompiler)
from platmap import build_index, classifier, nid_names, host_names, DEC
from capstone import Cs, CS_ARCH_ARM, CS_MODE_ARM, CS_MODE_THUMB
from capstone import arm as A

HEADERS = os.path.expanduser("~/Dev/vita/vita-headers/include")


def prototypes(root):
    """function name -> one-line declaration, from every header under root"""
    out = {}
    for p in glob.glob(os.path.join(root, "**", "*.h"), recursive=True):
        src = re.sub(r"/\*.*?\*/", "", open(p, errors="replace").read(), flags=re.S)
        src = re.sub(r"//[^\n]*", "", src)
        for m in re.finditer(r"([A-Za-z_][\w \*]*?)\b((?:sce|_sce)\w+)\s*\(([^;{]*?)\)\s*;", src):
            out.setdefault(m.group(2), re.sub(r"\s+", " ", f"{m.group(1).strip()} {m.group(2)}({m.group(3).strip()})"))
    return out


def accesses(mod, a, limit=0x300):
    """loads and stores through r0 (the object a setter/getter/init works on) in a short body"""
    code, base = mod.m.mem[mod.m.loads[0][2]], mod.m.loads[0][2]
    md = Cs(CS_ARCH_ARM, CS_MODE_THUMB if a & 1 else CS_MODE_ARM); md.detail = True
    st, ld = [], []
    for i in md.disasm(bytes(code[(a & ~1) - base:(a & ~1) - base + limit]), a & ~1):
        mem = [o for o in i.operands if o.type == A.ARM_OP_MEM]
        if mem and i.reg_name(mem[0].mem.base) == "r0":
            (st if i.mnemonic.startswith(("str", "vstr")) else ld if i.mnemonic.startswith(("ldr", "vldr")) else []).append((i.mnemonic, mem[0].mem.disp))
        if i.mnemonic == "bx" or ("pc" in i.op_str and i.mnemonic.startswith(("pop", "ldm"))):
            break
    return st, ld


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    opt = lambda k, d=None: sys.argv[sys.argv.index(k) + 1] if k in sys.argv else d
    outp, hdr = opt("--out"), opt("--headers", HEADERS)
    for v in (outp, hdr):
        if v in args: args.remove(v)
    if not args:
        print(__doc__); sys.exit(1)
    names, host = nid_names(), host_names()
    nm = lambda k: names.get(k, f"{k[0]}_{k[1]:08X}")
    kernel, users = build_index()
    classify, mod = classifier(kernel, users)
    target = args[0]
    if not os.path.exists(target):   # a library name: the module exporting it
        target = next((p for (lib, nid), p in users.items() if lib == target), None)
        if not target:
            sys.exit(f"no module in {DEC} exports {args[0]}")
    m = mod(target)
    protos = prototypes(hdr) if os.path.isdir(hdr) else {}

    rows = []
    for (lib, nid), a in sorted(m.exports.items(), key=lambda kv: nm(kv[0])):
        s, u = classify((lib, nid))
        size = sum(m.an.function(a & ~1, not a & 1, m.entries)[0].values()) if m.an.function(a & ~1, not a & 1, m.entries) else 0
        rows.append((lib, nm((lib, nid)), a, "BOUNDARY" if s else "PURE", size, sorted(nm(k) for k in s), len(u)))

    w = (open(outp, "w") if outp else sys.stdout).write
    libs = sorted({r[0] for r in rows})
    npure = sum(r[3] == "PURE" for r in rows)
    w(f"# {m.name} porting map\n\nGenerated by `dev/research/libmap.py` from `{os.path.relpath(target, DEC)}`"
      f" (exports {', '.join(f'`{l}`' for l in libs)}). {len(rows)} functions: **{npure} PURE**, **{len(rows) - npure} BOUNDARY**."
      " The host implements a BOUNDARY function's system calls, not the function.\n\n")
    calls = defaultdict(list)
    for r in rows:
        for c in r[5]: calls[c].append(r[1])
    w(f"## System calls under it ({len(calls)})\n\n| system call | kernel module | used by | host today |\n|---|---|---|---|\n")
    rev = {nm(k): v for k, v in kernel.items()}
    for c in sorted(calls, key=lambda c: (rev.get(c, ""), c)):
        fns = sorted(set(calls[c]))
        w(f"| `{c}` | {rev.get(c, '?')} | {', '.join(f'`{f}`' for f in fns[:6])}{' …' if len(fns) > 6 else ''} ({len(fns)}) | {'yes' if c in host else '-'} |\n")
    w("\n## Functions\n\n| function | class | size | system calls | host today | signature |\n|---|---|---|---|---|---|\n")
    for lib, name, a, cls, size, sc, nu in rows:
        w(f"| `{name}` | {cls} | {size} | {len(sc)}{f' (+{nu} unresolved)' if nu else ''} | {'yes' if name in host else '-'} | `{protos.get(name, '?')}` |\n")
    # object layouts from the small functions' r0 accesses
    lay = defaultdict(lambda: [set(), set()])
    for lib, name, a, cls, size, sc, nu in rows:
        if size and size <= 160:
            st, ld = accesses(m, a)
            for mn, d in st: lay[name][0].add(d)
            for mn, d in ld: lay[name][1].add(d)
    if lay:
        w("\n## Object layouts (small functions' accesses through their first argument)\n\n| function | stores | loads | signature |\n|---|---|---|---|\n")
        for name in sorted(lay):
            st, ld = lay[name]
            if st or ld:
                w(f"| `{name}` | {' '.join(f'+{d:#x}' for d in sorted(st)) or '-'} | {' '.join(f'+{d:#x}' for d in sorted(ld)) or '-'} | `{protos.get(name, '?')}` |\n")


if __name__ == "__main__":
    main()
