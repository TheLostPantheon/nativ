#!/bin/zsh
# Test-only GLSL fixtures -> committed SPIR-V words, so running the test needs no shader compiler.
set -e
cd ${0:A:h}
out=../metal_smoke_spirv.h
tmp=$(mktemp -d)
trap 'rm -rf -- "$tmp"' EXIT

compile() {
	if command -v glslc >/dev/null; then
		glslc -O --target-env=vulkan1.1 -o "$2" "$1"
	elif command -v glslangValidator >/dev/null; then
		glslangValidator -V --target-env vulkan1.1 -Os -o "$2" "$1" >/dev/null
	else
		echo "install glslc or glslangValidator to rebuild the Metal smoke shaders" >&2
		exit 1
	fi
}

print "/* generated by runtime/tests/shaders/build.sh -- edit the GLSL there, not this file */" > "$out"
print "#include <stdint.h>" >> "$out"
for f in metal_smoke.vert metal_base.frag metal_fetch.frag; do
	n=${f:r}_${f:e}
	compile "$f" "$tmp/$n.spv"
	print "static const uint32_t ${n}[] = {" >> "$out"
	od -An -v -t x4 "$tmp/$n.spv" | awk '{ for (i = 1; i <= NF; i++) printf "0x%s,", $i; print "" }' >> "$out"
	print "};" >> "$out"
done
print "generated $out"
