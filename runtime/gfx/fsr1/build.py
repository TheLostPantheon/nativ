#!/usr/bin/env python3
"""Compile Nativ's FidelityFX FSR1 EASU and RCAS shaders into fsr1_shaders.h."""
import os
import shutil
import struct
import subprocess
import tempfile


HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
FFX = os.path.join(ROOT, "third_party", "fidelityfx", "gpu")
OUT = os.path.join(HERE, "..", "fsr1_shaders.h")


def tool(name):
    found = shutil.which(name)
    if not found:
        raise SystemExit(f"{name} not found")
    return found


def main():
    glslang = tool("glslangValidator")
    spirv_opt = tool("spirv-opt")
    modules = []
    with tempfile.TemporaryDirectory() as temp:
        for name in ("easu", "rcas"):
            source = os.path.join(HERE, name + ".glsl")
            spirv = os.path.join(temp, name + ".spv")
            subprocess.run(
                [glslang, "-S", "comp", "--target-env", "vulkan1.1", "-I" + FFX, "-o", spirv, source],
                check=True,
            )
            subprocess.run([spirv_opt, "--strip-debug", spirv, "-o", spirv], check=True)
            data = open(spirv, "rb").read()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            modules.append((name, words))

    with open(OUT + ".tmp", "w", newline="\n") as out:
        out.write("/* generated by runtime/gfx/fsr1/build.py from AMD FidelityFX FSR1 (MIT) -- don't edit */\n")
        out.write("#include <stdint.h>\n")
        for name, words in modules:
            out.write(f"static const uint32_t fsr1_{name}[] = {{\n")
            for i in range(0, len(words), 8):
                out.write("\t" + "".join(f"0x{word:08x}," for word in words[i:i + 8]) + "\n")
            out.write("};\n")
    os.replace(OUT + ".tmp", OUT)
    print(f"{len(modules)} modules -> {OUT}")


if __name__ == "__main__":
    main()
