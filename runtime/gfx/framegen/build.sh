#!/bin/bash
# build.sh: frame generation's compute passes (*.comp) compiled to SPIR-V with glslangValidator into ../framegen_shaders.h.
# Run it after changing a pass and commit the header (a player's build doesn't compile GLSL). Metal takes the same
# SPIR-V through SPIRV-Cross at run time (framegen.c). Needs glslangValidator and spirv-opt.
set -e
D=$(cd "$(dirname "$0")" && pwd); OUT=$D/../framegen_shaders.h
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
{
  echo "/* generated by runtime/gfx/framegen/build.sh from the passes there -- don't edit */"
  echo "#include <stdint.h>"
  for p in reduce search pick warp stat; do
    glslangValidator -S comp --target-env vulkan1.1 -I"$D" -o "$T/x.spv" "$D/$p.comp" >"$T/log" || { cat "$T/log" >&2; exit 1; }
    spirv-opt -O --strip-debug "$T/x.spv" -o "$T/x.spv"
    echo "static const uint32_t fg_$p[] = {"
    od -An -v -tx4 "$T/x.spv" | awk '{ for (i = 1; i <= NF; i++) printf "0x%s,", $i; printf "\n" }'
    echo "};"
  done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "$(grep -c 'static const' "$OUT") passes, $(wc -c < "$OUT") bytes -> $OUT"
