#!/bin/bash
# build.sh: FSR 3.1's passes (passes/*.glsl, from passes.py) and clears.glsl compiled to SPIR-V with glslangValidator, every permutation
# Nativ uses, into ../fsr_shaders.h -- run it after changing the passes or ffx_fsr3upscaler_callbacks_nativ.h, and
# commit the header (a player's build doesn't compile GLSL). Permutations: HDR colour input (a float main target) x
# inverted depth (a game drawing with GREATER) x FP16 or not; the vectors at the render size (the SDK's usual case; at native AA the
# same thing), the
# vectors without jitter (the motion pass leaves it out), Lanczos LUT reprojection, SPD with its quad shuffles (Metal's
# quad_shuffle; a Vulkan device without subgroup quad operations fails the pipeline and FSR says so and stays off). Needs glslangValidator and spirv-opt,
# python3 (a real one: Windows' Store alias stub fails here), od and awk. The passes are listed below, not globbed, so the header's order doesn't depend on
# the shell's locale; a passes/*.glsl missing from the list stops the build.
set -e
D=$(cd "$(dirname "$0")" && pwd); FFX=$D/../../../third_party/fidelityfx/gpu; OUT=$D/../fsr_shaders.h
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
python3 "$D/passes.py" >/dev/null
PASSES="accumulate_sharpen accumulate autogen_reactive debug_view luma_instability luma_pyramid prepare_inputs prepare_reactivity rcas shading_change_pyramid shading_change"
for p in "$D"/passes/*.glsl; do   # (passes.py wrote one per pass: each must be in PASSES, or fsr.c would build without it)
  case " $PASSES " in *" $(basename "$p" .glsl) "*) ;; *) echo "build.sh: $p is not in PASSES" >&2; exit 1 ;; esac
done
COMMON="-DFFX_GPU=1 -DFFX_GLSL=1
 -DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_SAMPLERS_USE_DATA_HALF=0 -DFFX_FSR3UPSCALER_OPTION_ACCUMULATE_SAMPLERS_USE_DATA_HALF=0
 -DFFX_FSR3UPSCALER_OPTION_POSTPROCESSLOCKSTATUS_SAMPLERS_USE_DATA_HALF=0
 -DFFX_FSR3UPSCALER_OPTION_UPSAMPLE_USE_LANCZOS_TYPE=2 -DFFX_FSR3UPSCALER_OPTION_REPROJECT_USE_LANCZOS_TYPE=1
 -DFFX_FSR3UPSCALER_OPTION_LOW_RESOLUTION_MOTION_VECTORS=1 -DFFX_FSR3UPSCALER_OPTION_JITTERED_MOTION_VECTORS=0"   # (sharpening: in each pass file, passes.py)
{
  echo "/* generated by runtime/gfx/fsr/build.sh from FSR 3.1's passes (FidelityFX SDK v1.1.4, MIT: third_party/fidelityfx) -- don't edit */"
  echo "#include <stdint.h>"
  for n in $PASSES; do
    p="$D/passes/$n.glsl"
    for half in 0 1; do for hdr in 0 1; do for inv in 0 1; do   # (half: FP16 arithmetic, for Metal; SDL's Vulkan device may not enable shaderFloat16)
      glslangValidator -S comp --target-env vulkan1.1 -I"$D" -I"$FFX" -I"$FFX/fsr3upscaler" $COMMON -DFFX_HALF=$half -DFFX_FSR3UPSCALER_OPTION_REPROJECT_SAMPLERS_USE_DATA_HALF=$half \
        -DFFX_FSR3UPSCALER_OPTION_HDR_COLOR_INPUT=$hdr -DFFX_FSR3UPSCALER_OPTION_INVERTED_DEPTH=$inv -o "$T/x.spv" "$p" >"$T/log" || { cat "$T/log" >&2; exit 1; }
      spirv-opt --strip-debug "$T/x.spv" -o "$T/x.spv"   # (names only: a quarter of the size)
      echo "static const uint32_t fsr_${n}_h${hdr}_i${inv}$([ $half = 1 ] && echo _f16)[] = {"
      od -An -v -tx4 "$T/x.spv" | awk '{ for (i = 1; i <= NF; i++) printf "0x%s,", $i; printf "\n" }'
      echo "};"
    done; done; done
  done
  for x in clears; do   # (Nativ's own: the per-frame clears)
    glslangValidator -S comp --target-env vulkan1.1 -o "$T/x.spv" "$D/$x.glsl" >"$T/log" || { cat "$T/log" >&2; exit 1; }
    echo "static const uint32_t fsr_$x[] = {"
    od -An -v -tx4 "$T/x.spv" | awk '{ for (i = 1; i <= NF; i++) printf "0x%s,", $i; printf "\n" }'
    echo "};"
  done
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "$(grep -c 'static const' "$OUT") modules, $(wc -c < "$OUT") bytes -> $OUT"
