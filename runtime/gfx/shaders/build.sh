#!/bin/zsh
# The renderer's built-in shaders for Vulkan (Linux, Windows, Android): GLSL here -> SPIR-V words in
# ../vk_shaders.h, which is committed, so a build never needs a shader compiler. Metal keeps its MSL
# twins in gfx_gpu.c / post.c; a change to one side is made to the other. Needs glslc (shaderc).
set -e
cd ${0:A:h}
out=../vk_shaders.h; tmp=$(mktemp -d)
print "/* generated by runtime/gfx/shaders/build.sh from the GLSL there (glslc) -- don't edit; edit the GLSL and rerun */" > $out
print "#include <stdint.h>" >> $out
for f in *.vert *.frag; do
	n=${f:r}_${f:e}
	glslc -O --target-env=vulkan1.1 -o $tmp/$n.spv $f
	print "static const uint32_t vk_${n}[] = {" >> $out
	od -An -v -t x4 $tmp/$n.spv | awk '{ for (i = 1; i <= NF; i++) printf "0x%s,", $i; print "" }' >> $out
	print "};" >> $out
done
rm -rf $tmp
print "generated $out"
